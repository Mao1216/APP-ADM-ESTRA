create table if not exists public.indicator_site_assignments (
  id bigint generated by default as identity primary key,
  indicator_id bigint not null references public.indicators(id) on delete cascade,
  site_id bigint not null references public.sites(id),
  responsible_email text not null,
  weight numeric not null default 1 check (weight > 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(indicator_id, site_id)
);

create index if not exists indicator_site_assignments_indicator_idx
  on public.indicator_site_assignments(indicator_id, active);
create index if not exists indicator_site_assignments_responsible_idx
  on public.indicator_site_assignments(lower(responsible_email), active);

alter table public.indicator_reports
  add column if not exists site_assignment_id bigint references public.indicator_site_assignments(id) on delete cascade;
create index if not exists indicator_reports_assignment_period_idx
  on public.indicator_reports(site_assignment_id, indicator_id, period);

