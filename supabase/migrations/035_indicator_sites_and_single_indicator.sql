create or replace function public.can_report_site_indicator(indicator bigint, assignment bigint)
returns boolean language sql stable security definer set search_path=public as $$
  select auth.uid() is not null and (
    is_gcg() or is_super_admin() or exists (
      select 1 from public.indicator_site_assignments a
      where a.id = assignment and a.indicator_id = indicator and a.active
        and person_matches(a.responsible_email)
    )
  );
$$;

-- Reemplaza la validación anterior para permitir el mismo periodo en sedes distintas.
create or replace function public.prepare_measurement()
returns trigger language plpgsql security definer set search_path=public as $$
declare i indicators;
begin
  select * into strict i from public.indicators where id = new.indicator_id for update;
  if tg_op = 'INSERT' and exists (
    select 1 from public.indicator_reports r
    where r.indicator_id = new.indicator_id
      and coalesce(r.site_assignment_id, 0) = coalesce(new.site_assignment_id, 0)
      and public.indicator_period_date(r.period) = public.indicator_period_date(new.period)
  ) then raise exception 'Este periodo ya fue registrado para esta sede.'; end if;
  perform public.indicator_period_date(new.period);
  if tg_op = 'INSERT' then
    new.measurement_target = i.target; new.measurement_comparator = i.comparator;
  else
    new.measurement_target = coalesce(old.measurement_target, new.measurement_target);
    new.measurement_comparator = coalesce(old.measurement_comparator, new.measurement_comparator);
  end if;
  new.status = case when new.result is null then 'Sin datos'
    else public.measurement_status(new.result, coalesce(new.measurement_target, i.target), coalesce(new.measurement_comparator, i.comparator)) end;
  return new;
end $$;

create or replace function public.register_site_indicator_measurement(
  indicator bigint, assignment bigint, report_period text, report_result numeric, report_observations text default null
) returns bigint language plpgsql security definer set search_path=public as $$
declare result_id bigint;
begin
  if not public.can_report_site_indicator(indicator, assignment) then
    raise exception 'Tu cuenta no está asignada para reportar este indicador en esta sede';
  end if;
  if not exists(select 1 from public.indicators where id=indicator and approval_status='Aprobado') then
    raise exception 'El indicador debe estar aprobado antes de registrar resultados';
  end if;
  if not exists(select 1 from public.indicator_site_assignments where id=assignment and indicator_id=indicator and active) then
    raise exception 'La asignación de sede no es válida';
  end if;
  insert into public.indicator_reports(indicator_id, site_assignment_id, period, result, status, registered_date, observations, created_by)
  values(indicator, assignment, trim(report_period), report_result, 'Sin datos', current_date,
    case when report_result is null then null else nullif(trim(report_observations),'') end, auth.uid())
  returning id into result_id;
  return result_id;
end $$;
revoke all on function public.register_site_indicator_measurement(bigint,bigint,text,numeric,text) from public, anon;
grant execute on function public.register_site_indicator_measurement(bigint,bigint,text,numeric,text) to authenticated;

notify pgrst, 'reload schema';
commit;
