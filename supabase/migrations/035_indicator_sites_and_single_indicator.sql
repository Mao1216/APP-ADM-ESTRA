-- Un objetivo conserva una única definición de indicador. Las sedes usan asignaciones,
-- no indicadores duplicados.
create or replace function public.enforce_one_indicator_per_objective()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if exists (select 1 from public.indicators where objective_id = new.objective_id) then
    raise exception 'Cada objetivo puede tener únicamente un indicador.';
  end if;
  return new;
end $$;

drop trigger if exists enforce_one_indicator_per_objective on public.indicators;
create trigger enforce_one_indicator_per_objective
before insert on public.indicators
for each row execute function public.enforce_one_indicator_per_objective();

create table if not exists public.sites (
  id bigint generated by default as identity primary key,
  name text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

insert into public.sites(name) values ('Biomont'), ('Kunthur')
