-- Indicadores core: hasta cuatro indicadores prioritarios definidos por GCG.
begin;

create table if not exists public.core_indicators (
  id bigint generated by default as identity primary key,
  indicator_id bigint not null unique references public.indicators(id) on delete cascade,
  position smallint not null unique check (position between 1 and 4),
  selected_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.core_indicators enable row level security;
drop policy if exists "Read core indicators" on public.core_indicators;
drop policy if exists "GCG manages core indicators" on public.core_indicators;
create policy "Read core indicators" on public.core_indicators for select to authenticated using (true);
create policy "GCG manages core indicators" on public.core_indicators for all to authenticated using (is_gcg()) with check (is_gcg());

create or replace function public.set_core_indicators(selected_indicator_ids bigint[])
returns void language plpgsql security definer set search_path=public as $$
declare selected_count integer; indicator_id bigint; position_index integer := 0;
begin
  if auth.uid() is null or not is_gcg() then
    raise exception 'Solo GCG puede actualizar los indicadores core';
  end if;
  selected_count := coalesce(array_length(selected_indicator_ids, 1), 0);
  if selected_count > 4 then raise exception 'Puedes seleccionar como máximo cuatro indicadores core'; end if;
  if selected_count <> (select count(distinct item) from unnest(coalesce(selected_indicator_ids, '{}'::bigint[])) item) then
    raise exception 'No se puede repetir un indicador core';
  end if;
  if exists (
    select 1 from unnest(coalesce(selected_indicator_ids, '{}'::bigint[])) item
    where not exists (select 1 from public.indicators i where i.id = item)
  ) then raise exception 'Uno de los indicadores seleccionados ya no existe'; end if;

  delete from public.core_indicators;
  foreach indicator_id in array coalesce(selected_indicator_ids, '{}'::bigint[]) loop
    position_index := position_index + 1;
    insert into public.core_indicators(indicator_id, position, selected_by)
    values(indicator_id, position_index, auth.uid());
  end loop;
end $$;
revoke all on function public.set_core_indicators(bigint[]) from public, anon;
grant execute on function public.set_core_indicators(bigint[]) to authenticated;

notify pgrst, 'reload schema';
commit;
